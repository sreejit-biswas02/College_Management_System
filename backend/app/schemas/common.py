"""Shared Pydantic pagination and common response schemas."""

import math

from pydantic import BaseModel


class PaginatedResponse[T](BaseModel):
    """Standard paginated list response."""

    items: list[T]
    total: int
    page: int
    page_size: int
    pages: int

    @classmethod
    def create(
        cls,
        items: list[T],
        total: int,
        page: int,
        page_size: int,
    ) -> "PaginatedResponse[T]":
        """Construct a PaginatedResponse computing total pages."""
        pages = math.ceil(total / page_size) if total > 0 else 0
        return cls(
            items=items,
            total=total,
            page=page,
            page_size=page_size,
            pages=pages,
        )
